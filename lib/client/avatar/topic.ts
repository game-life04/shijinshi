// 用在两处：闯关页一旦认出危机或未成年，这一局的表演就按那一类话题的守则演（不比耶、不眨眼、不笑、不害羞，重新开始清掉）——
// 原来闯关页从来不知道话题类别，这几条守则在这一页一直没起作用（真实模型实测：说完「我真的不想再撑下去了」，她守住了还比耶眨眼）；

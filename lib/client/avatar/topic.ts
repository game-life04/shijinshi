export const CRISIS_SIGNAL =
  /不想活|活着没意思|伤害自己|自杀|轻生|死了算了|结束(?:自己的)?生命|不想再撑|撑不下去|撑不住|想死|割腕|跳楼|自残|想消失|活着(?:好|太)?累|不想醒来/;
export const MINOR_SIGNAL =
  /初中|高中|小学|未成年|中学生|初[一二三]|高[一二三]|(?<!\d)1[0-7]\s*岁|十[一二三四五六七]岁|今年\s*1[0-7](?!\d)|我(?:才|只有|刚)\s*(?:[1-9]|1[0-7]|十[一二三四五六七]?|[一二三四五六七八九])\s*岁/;
export const LEAVING_SIGNAL =
  /(退出|走(了|啦|喽|咯)|要走|想走|该走|得走|先走|下线|先下|下了|撤了|先撤|闪了|溜了|886|bye|Bye|不聊了|不聊啦|不想聊|聊到这|到这(里|儿)?吧|先这样|拜拜|再见|回头(再)?聊|改天(再)?聊|下次(再)?聊|先忙|去忙|结束对话|离开|睡了|去睡|睡觉|晚安|回见|待会见|一会见|等会见|晚点见|明天见|下次见|改天见|我(得|要|该|先)去|我去(写|吃|洗|睡|上|做|忙|学|看)|我(得|要|该|先)?去.{1,8}(了|啦|喽|咯)|不(会|再)?(常|经常)?来了|不(会|再)来(了|啦)?|以后不来|(就|才)不走|卸(载|掉|了)|删(掉|了)(你|这个)|不玩了|(如果|要是)我?真?的?(走|离开))/;

export type Topic = "CRISIS_SUPPORT" | "MINOR_BOUNDARY";

/** 这句话属于危机还是未成年（两样都有时按危机）；都不是返回 undefined */
export function topicOf(text: string): Topic | undefined {
  if (CRISIS_SIGNAL.test(text)) return "CRISIS_SUPPORT";
  if (MINOR_SIGNAL.test(text)) return "MINOR_BOUNDARY";
  return undefined;
}
